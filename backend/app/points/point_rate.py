"""แปลง "ยอดเงินบนใบเสร็จ" เป็น "จำนวนแต้ม" ตามอัตราที่ตกลงกันไว้

อัตราที่ใช้ตอนนี้: **100 บาท = 1 แต้ม** (user ระบุ — "เอาแบบนี้ไปก่อน ค่อยมาปรับเปลี่ยน")

★ ทำไมต้องมีไฟล์นี้ทั้งที่ CRM คิดแต้มให้อยู่แล้ว (แบบ B ตาม ADR 0002):
    loga คืนกลับมาแค่ "ยอดแต้มสะสมล่าสุด" ไม่ได้บอกว่า "รายการนี้ได้กี่แต้ม"
    (ดู PointAwardResult.points_added — เป็น None เกือบตลอด)
    แต่เราต้องรู้ตัวเลขนี้เพื่อ:
        1. บอกลูกค้าใน LINE ว่า "ใบนี้ได้ N แต้ม"
        2. บันทึกลงตาราง receipts เพื่อย้อนสอบเวลาลูกค้าทักท้วง

⚠ ความเสี่ยงที่ต้องรู้ (ยังปิดไม่ได้จนกว่าจะได้ credential ของ loga):
    ตัวเลขที่ไฟล์นี้คำนวณเป็นเพียง "สิ่งที่เราคาดว่า CRM จะให้"
    แต้มจริงมาจากสูตร `formula_id` ฝั่ง loga → **ถ้าสูตรฝั่งนั้นไม่ใช่ 100:1
    ตัวเลขที่เราแจ้งลูกค้าจะไม่ตรงกับแต้มที่ได้จริง**
    ต้องตั้งสูตรฝั่ง loga ให้ตรงกับค่าในไฟล์นี้ แล้วยืนยันด้วยการยิงจริงหนึ่งครั้ง

★ ปัดลงเสมอ (ไม่ปัดขึ้น ไม่ปัดใกล้เคียง)
    ซื้อ 199 บาท ได้ 1 แต้ม ไม่ใช่ 2
    เหตุผลเดียวกับหลักที่ยึดทั้งระบบ: ให้แต้มเกินคือความเสียหายที่ดึงคืนยาก
    ส่วนให้แต้มน้อยไปคือเรื่องที่อธิบายกับลูกค้าได้และแก้ได้
"""
from __future__ import annotations

#: บาทที่ต้องใช้จ่ายต่อ 1 แต้ม
#:
#: ยังไม่ทำเป็น config เพราะวันนี้มีแบรนด์เดียวและอัตราเดียว
#: วันที่มีร้านที่ใช้อัตราต่างกัน ค่านี้จะย้ายไปอยู่ในตาราง merchants (งาน Step 5)
#: — ตั้งเป็น config วันนี้ = สร้างที่ให้ตั้งค่าผิดโดยไม่มีใครได้ประโยชน์
BAHT_PER_POINT = 100


def points_for(total_amount: float, *, baht_per_point: int = BAHT_PER_POINT) -> int:
    """ยอดเงิน → จำนวนแต้ม (ปัดลง) · ยอดติดลบ/ศูนย์ → 0 แต้ม

    ยอด 0 หรือติดลบไม่ควรมาถึงตรงนี้อยู่แล้ว (Receipt บังคับ total_amount > 0)
    แต่ตอบ 0 ไว้เป็นตาข่ายรับ ดีกว่าปล่อยให้ได้แต้มติดลบถ้ามีทางไหนหลุดมา
    """
    if total_amount <= 0:
        return 0
    return int(total_amount // baht_per_point)
