"""แปลงเบอร์โทรให้เป็นรูปแบบมาตรฐานเดียว (canonical) ก่อนใช้เป็นกุญแจเชื่อมลูกค้า

★ ทำไมไฟล์เล็กๆ นี้สำคัญ:
    เบอร์คือกุญแจเดียวที่เชื่อม lineUserId ↔ loga cuid (ADR 0002)
    ถ้า "0812345678" กับ "+66812345678" ถูกเก็บเป็นคนละคน = ลูกค้าคนเดียวมีสองตัวตน
    แต้มกระจายสองที่ ระบบหาไม่เจอ ต้องมาตามแก้ทีหลังซึ่งเจ็บมาก
    → ทุกเบอร์ต้องผ่านที่นี่ก่อนเก็บ/ค้นเสมอ ไม่มีข้อยกเว้น

canonical = รูปแบบไทยท้องถิ่น 10 หลักขึ้นต้น 0 (เช่น 0812345678)
    เลือกแบบนี้เพราะ loga เป็นระบบไทย + เป็นรูปที่คนไทยและ SMS gateway คุ้นเคย

บังคับเป็น "มือถือ" (หลักที่สอง 6/8/9) เพราะระบบยืนยันตัวด้วย OTP ทาง SMS —
เบอร์บ้าน (02, 03, ...) รับ SMS ไม่ได้อยู่แล้ว จึงไม่รับตั้งแต่ต้น
"""
from __future__ import annotations

import re

from app.reliability.errors import InputValidationError

#: หลักที่สองของมือถือไทย (06x, 08x, 09x) — เบอร์บ้านขึ้น 02/03/... ไม่รับ
_MOBILE_SECOND_DIGITS = frozenset("689")

_THAI_MOBILE_LENGTH = 10


def normalize_phone(raw: str) -> str:
    """คืนเบอร์รูปแบบมาตรฐาน 0XXXXXXXXX · รูปที่ผิด → InputValidationError

    รับได้หลากหลายอย่างที่ลูกค้าพิมพ์จริง:
        "0812345678"      → "0812345678"
        "+66812345678"    → "0812345678"   (E.164 ตัด 0 นำหน้า)
        "081-234-5678"    → "0812345678"
        "081 234 5678"    → "0812345678"

    ปฏิเสธ: สั้น/ยาวผิด, เบอร์บ้าน, มีตัวอักษรปนที่ไม่ใช่ตัวคั่น
    """
    if not raw or not raw.strip():
        raise InputValidationError("กรุณากรอกเบอร์โทรศัพท์")

    digits = _to_local_digits(raw)

    if len(digits) != _THAI_MOBILE_LENGTH:
        raise InputValidationError("เบอร์โทรศัพท์ต้องมี 10 หลัก")
    if digits[0] != "0" or digits[1] not in _MOBILE_SECOND_DIGITS:
        # สื่อความให้ลูกค้าเข้าใจ ไม่ใช่ "หลักที่สองต้องเป็น 6/8/9" ซึ่งลูกค้าไม่รู้เรื่อง
        raise InputValidationError("กรุณากรอกเบอร์มือถือ (ขึ้นต้น 06, 08 หรือ 09)")

    return digits


def _to_local_digits(raw: str) -> str:
    """ลอกตัวคั่นทิ้ง + ยุบรหัสประเทศ 66 ให้เป็นรูปท้องถิ่นขึ้นต้น 0

    แยกออกมาเพื่อให้ normalize_phone อ่านเป็น "ตรวจความถูกต้อง" ล้วนๆ
    ไม่ปนกับเรื่องการแปลงรูปอักขระ
    """
    digits = re.sub(r"\D", "", raw)  # ลบทุกอย่างที่ไม่ใช่ตัวเลข (เว้นวรรค, -, (), +, ตัวอักษร)

    # +66812345678 / 66812345678 → รหัสประเทศไทย · ยุบ 66 นำหน้าให้กลับเป็น 0 ท้องถิ่น
    # เผื่อทั้งคนกรอกถูก (66 + 81...) และคนกรอกเกิน (66 + 081...)
    if digits.startswith("66"):
        rest = digits[2:]
        digits = rest if rest.startswith("0") else f"0{rest}"

    return digits
